    assert code == 0, payload["violations"]
    assert payload["counts"]["skipped_older_contract"] == 3
    assert payload["counts"]["skipped_v7"] == 3
    assert payload["denominators"]["gate_start"] == 1   # the v7 attempt is not in the population


