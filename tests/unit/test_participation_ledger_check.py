def test_a_malformed_line_is_a_named_violation_and_not_a_crash(tmp_path):
    path = write_ledger(tmp_path, healthy_rows())
    with path.open("a") as handle:
        handle.write("{not json at all\n")
        handle.write("[1, 2, 3]\n")
    code, payload = check(path)
    assert code == 1
    assert payload["violation_counts"]["malformed_line"] == 2
    assert payload["counts"]["unparsable_lines"] == 2
    # and the healthy lines around it were still graded
    assert payload["denominators"]["turn_start"] == 1


