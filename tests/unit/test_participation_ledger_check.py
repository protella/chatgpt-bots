def test_a_turn_outcome_is_never_counted_as_a_terminal(tmp_path):
    """THE POPULATION SEPARATION. This attempt has a turn_outcome carrying its attempt_id and no
    visible_action. If turn events could close an attempt, the terminal count would be 1 and the
    unmatched gate_start would vanish. Both denominators are reported, and neither moves."""
    rows = healthy_rows()
    del rows[row_index(rows, "visible_action")]
    code, payload = check(write_ledger(tmp_path, rows))
    assert code == 0, payload["violations"]
    assert payload["denominators"] == {"gate_start": 1, "visible_action": 0,
                                       "turn_start": 1, "turn_outcome": 1,
                                       "turn_start_dm": 0, "turn_outcome_dm": 0}
    assert "gate_start_without_terminal" in warning_names(payload)
    assert "turn_event_in_terminal_population" not in names(payload)


