"""The CV10 ledger checker — the thing the live battery trusts when it says a scenario passed.

Two properties matter here, and they pull in opposite directions:

1. It must FAIL, by name, on a broken join. A battery that reads "no violations" off a ledger
   whose turn events do not pair has learned nothing and will say it learned something.
2. It must not cry wolf on a HEALTHY ledger. The emitter omits None-valued fields rather than
   writing nulls, so half the schema is legitimately absent on any given line; a checker that
   demands every key would fire on every real file and be switched off within a day.

So the assertions are on violation NAMES (prose is free to change), and the headline fixture is
generated by CALLING THE REAL EMITTER — a checker validated only against hand-written fixtures
agrees with the fixture author rather than with the writer.

The checker itself is run as a SUBPROCESS, by path, from a directory that is not the repo. That is
not paranoia about imports: "runs against a ledger copied off a machine with no venv" is a
requirement, and a subprocess with only `tools/` on sys.path is the only way to test it.
"""
from __future__ import annotations

import json
import logging
import subprocess
import sys
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
CHECKER = REPO_ROOT / "tools" / "participation_ledger_check.py"

SESSION = "S1"


# ------------------------------------------------------------------------------ the harness

def run_checker(*paths, extra=()):
    """Run the CLI. cwd is deliberately NOT the repo, so a repo import would explode here."""
    argv = [sys.executable, str(CHECKER), *[str(p) for p in paths], *extra]
    return subprocess.run(argv, capture_output=True, text=True, cwd=str(Path(paths[0]).parent)
                          if paths else None)


def check(*paths):
    """(exit code, parsed --json report)."""
    result = run_checker(*paths, extra=("--json",))
    assert result.stderr == "", result.stderr
    return result.returncode, json.loads(result.stdout)


def names(payload):
    return set(payload["violation_counts"])


def warning_names(payload):
    return {w["name"] for w in payload["warnings"]}


def envelope(event, *, session=SESSION, version=10, contract="binary-v1", **fields):
    """One line, built the way `record()` builds it: None-valued fields are OMITTED."""
    row = {"v": version, "at": 1_700_000_000.0, "session": session, "event": event}
    if contract is not None:
        row["gate_contract"] = contract
    row.update({key: value for key, value in fields.items() if value is not None})
    return row


def stream_render_payload(**overrides):
    """Every §8 field, because every one of them is MANDATORY on a stream_render row.

    A fixture carrying a handful of fields was legal until the checker learned the contract;
    once it did, a minimal row is exactly the defect the contract exists to catch, so the
    fixtures widen in the same change that makes the fields mandatory rather than after it.
    """
    payload = {
        "channel_id": "C1", "H": "1.9",
        "periphery_floor_ts": "1.0", "inventory_start_ts": "0.5", "inventory_state": "warm",
        "stream_sha256": "f" * 64, "union_sha256": "e" * 64,
        "serializer_config_hash": "d" * 64, "sidecar_versions_hash": "c" * 64,
        "actor_map_hash": "b" * 64, "receipts_membership_hash": "a" * 64,
        "capability_profile_hash": "9" * 64,
        "byte_count": 420, "origin_byte_count": 120, "message_count": 7, "origin_count": 2,
        "candidate_count": 9, "root_count": 3, "orphan_root_count": 0,
        "receipts_included_count": 1, "receipts_excluded_count": 0,
        "history_pages": 1, "reply_pages": 0, "origin_pages": 1,
        "selection_version": 1, "serializer_version": 3,
        "reselected": False, "anchor_advanced": False,
    }
    payload.update(overrides)
    return payload


def healthy_rows(session=SESSION):
    """One gated channel turn that answered, start to finish, with every v8 event present.

    Ids are derived from the session, because they are unique per PROCESS in the real ledger and
    a fixture that reuses them across two sessions manufactures duplicate-join violations.
    """
    turn_id, attempt_id = f"t-{session}", f"a-{session}"
    return [
        envelope("session_start", session=session, build="deadbee"),
        envelope("gate_start", session=session, channel_id="C1", trigger_ts="1.0",
                 attempt_id=attempt_id, level="judicious"),
        envelope("gate_decision", session=session, channel_id="C1", trigger_ts="1.0",
                 attempt_id=attempt_id, wake=True, model="gpt-5.6-luna"),
        envelope("turn_start", session=session, channel_id="C1", trigger_ts="1.0",
                 turn_id=turn_id, surface="channel", gated=True, attempt_id=attempt_id),
        envelope("stream_render", session=session, trigger_ts="1.0",
                 turn_id=turn_id, origin_thread_ts="1.0", **stream_render_payload()),
        envelope("model_response", session=session, turn_id=turn_id, attempt_seq=1, status="ok",
                 model="gpt-5.6-sol", input_tokens=100, output_tokens=10),
        envelope("outbound_receipt", session=session, channel_id="C1", message_ts="2.0",
                 owner_turn_id=turn_id, op="register", prior_state="absent",
                 new_state="in_flight", applied=True),
        envelope("turn_outcome", session=session, channel_id="C1", trigger_ts="1.0",
                 turn_id=turn_id, attempt_id=attempt_id, kind="reply", chars=12,
                 detached_started=False, stream_build_present=True,
                 destinations=[{"channel_id": "C1", "thread_root_ts": "1.0", "first_ts": "2.0",
                                "state": "committed", "chars": 12, "kind": "reply"}],
                 edits=[]),
        envelope("visible_action", session=session, channel_id="C1", trigger_ts="1.0",
                 kind="reply", attempt_id=attempt_id, gate_woke=True, responder_started=True,
                 reaction_visible=False, destination="thread",
                 destination_source="structural"),
        envelope("session_end", session=session),
    ]


def write_ledger(tmp_path, rows, name="participation.jsonl"):
    path = tmp_path / name
    path.write_text("".join(json.dumps(row) + "\n" for row in rows))
    return path


def row_index(rows, event):
    return next(i for i, row in enumerate(rows) if row["event"] == event)


# ------------------------------------------------------------------------ the healthy ledger

def test_a_ledger_written_by_the_real_emitter_passes(tmp_path):
    """THE ROUND TRIP. Everything else here is a fixture I wrote; this one is the file the bot
    actually writes, through the real `record()`, the real omit-None rule, the real
    `emit_turn_outcome` assembler and the real `finish_attempt` terminal guard."""
    from config import config
    from message_processor import participation_telemetry as pt
    from message_processor.turn_runtime import DestinationRecord

    named = logging.getLogger(pt._SINK_LOGGER_NAME)
    saved = named.handlers[:]
    pt.shutdown()
    try:
        with patch.object(config, "log_directory", str(tmp_path)), \
                patch.object(config, "enable_participation_telemetry", True):
            pt.initialize()
            pt.gate_start("C1", "1.0", attempt_id="a1", level="judicious", thread_reply=False)
            pt.gate_decision("C1", "1.0", wake=True, attempt_id="a1", gate_ms=900,
                             classifier_ms=400, source_count=1)
            pt.turn_start("C1", "1.0", turn_id="t1", origin_thread_ts="1.0", surface="channel",
                          gated=True, attempt_id="a1")
            # THE FULL FIELD SET, exactly as `_emit_stream_render` sends it in production —
            # it splats `stream.stream_render_fields()`, so a hand-call carrying a handful of
            # fields would make this round trip prove less than the real path does.
            pt.stream_render(turn_id="t1", origin_thread_ts="1.0", trigger_ts="1.0",
                             **stream_render_payload())
            pt.model_response(turn_id="t1", attempt_seq=1, status="ok", model="gpt-5.6-sol",
                              input_tokens=100, output_tokens=10, cached_input_tokens=64)
            pt.outbound_receipt(channel_id="C1", message_ts="2.0", owner_turn_id="t1",
                                op="register", prior_state="absent", new_state="in_flight",
                                applied=True)

            # The real assembler, over the real destination record.
            record = DestinationRecord(channel_id="C1", thread_root_ts="1.0", first_ts="2.0",
                                       kind="reply")
            record.state = "committed"
            record.chars = 12
            turn = SimpleNamespace(turn_id="t1", destinations=[record], turn_error=None,
                                   H="1.9", stream_build_present=True)
            assert pt.emit_turn_outcome(turn, channel_id="C1", trigger_ts="1.0", kind="reply",
                                        attempt_id="a1")

            # The real terminal path, closed-flag guard and all.
            message = SimpleNamespace(metadata={pt.ATTEMPT_KEY: "a1", "ts": "1.0"},
                                      channel_id="C1", thread_id="1.0")
            assert pt.finish_attempt(message, "reply", reaction_visible=False)
            pt._drain()
            pt.shutdown()   # writes session_end and drains it

            ledger = tmp_path / pt.LOG_NAME
            code, payload = check(ledger)
            assert payload["violations"] == []
            assert payload["warnings"] == []
            assert code == 0, payload
            assert payload["counts"]["graded_lines"] > 0
    finally:
        pt.shutdown()
        named.handlers = saved


def test_the_handwritten_healthy_fixture_agrees_with_the_emitter(tmp_path):
    code, payload = check(write_ledger(tmp_path, healthy_rows()))
    assert (code, payload["violations"], payload["warnings"]) == (0, [], [])
    assert payload["verdict"] == "pass" and payload["ok"] is True


def test_legal_absences_are_not_violations(tmp_path):
    """The emitter omits None. A minimal-but-honest turn — no chars, no error, no H, an ungated
    turn with no attempt_id, a receipt with no prior state, a destination whose thread root and
    char count are null — is HEALTHY."""
    rows = [
        envelope("session_start", build="deadbee"),
        envelope("turn_start", channel_id="C1", trigger_ts="1.0", turn_id="t9",
                 surface="channel", gated=False),
        envelope("turn_outcome", channel_id="C1", trigger_ts="1.0", turn_id="t9",
                 kind="silence", detached_started=False, stream_build_present=False,
                 destinations=[{"channel_id": "C1", "thread_root_ts": None, "first_ts": "2.0",
                                "state": "observed", "chars": None, "kind": "stream"}],
                 edits=[]),
        envelope("outbound_receipt", channel_id="C1", message_ts="2.0", owner_turn_id="t9",
                 op="pending_resolve", new_state="finalized", applied=True),
        envelope("session_end"),
    ]
    code, payload = check(write_ledger(tmp_path, rows))
    assert (code, payload["violations"]) == (0, [])


